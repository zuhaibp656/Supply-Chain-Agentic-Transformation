def _write_table(name: str, rows: List[Dict[str, Any]]) -> None:
    XYZ_TABLES_DIR.mkdir(parents=True, exist_ok=True)
    json_path = XYZ_TABLES_DIR / f"{name}.json"
    csv_path = XYZ_TABLES_DIR / f"{name}.csv"
    json_path.write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")

    if rows:
        fieldnames = list(rows[0].keys())
        for r in rows:
            for k in r.keys():
                if k not in fieldnames:
                    fieldnames.append(k)
        with csv_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            for r in rows:
                writer.writerow(
                    {
                        k: json.dumps(r.get(k)) if isinstance(r.get(k), (list, dict)) else r.get(k, "")
                        for k in fieldnames
                    }
                )


